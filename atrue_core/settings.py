# ``TabSessionMiddleware`` must sit directly below ``SessionMiddleware`` so that
# it can swap ``request.session`` for the calling tab's session *before* any
# other per-request state is derived from it. Everything below it therefore
# becomes per-tab for free:
#
#   * ``CsrfViewMiddleware``      -> CSRF tokens are per-tab (see below);
#   * ``AuthenticationMiddleware`` -> ``request.user`` is resolved from the
#                                     tab's session, not the shared cookie;
#   * ``MessageMiddleware``       -> the message queue is per-tab.
#
# Placing it last (after all of the above) is what made authentication look
# isolated while login in one tab still broke every other tab: ``login()``
# rotates the CSRF token, and a browser-wide CSRF cookie is a single shared
# secret, so signing in on one tab invalidated the tokens already sitting in
# the other tabs' forms and their next POST failed with HTTP 403.
MIDDLEWARE = [
    'django.middleware.security.SecurityMiddleware',
    'django.contrib.sessions.middleware.SessionMiddleware',
    'atrue_core.middleware.TabSessionMiddleware',
    'django.middleware.common.CommonMiddleware',
    'django.middleware.csrf.CsrfViewMiddleware',
    'django.contrib.auth.middleware.AuthenticationMiddleware',
    'django.contrib.messages.middleware.MessageMiddleware',
    'django.middleware.clickjacking.XFrameOptionsMiddleware',
]

# Keep the CSRF secret in the session rather than in a cookie.
#
# The CSRF cookie is shared by every tab in the browser profile, and
# ``django.contrib.auth.login()`` rotates the token on every sign-in. With a
# cookie that rotation reaches all tabs at once and invalidates the tokens
# already rendered in their pages. Because ``TabSessionMiddleware`` hands
# ``CsrfViewMiddleware`` the calling tab's session, storing the secret in the
# session scopes the rotation to that one tab: signing in, signing out or
# submitting a form in tab 1 cannot invalidate a token held by tab 2.
CSRF_USE_SESSIONS = True

# Keep queued messages in the session as well.
#
# The default ``FallbackStorage`` prefers a *cookie*, and cookies are shared by
# every tab in the browser profile. The message queue is therefore global, and
# the first tab to render a page silently consumes it: signing out of one tab
# would pop "You have been signed out" in another tab that is still signed in,
# purely because that tab happened to refresh first. Because
# ``TabSessionMiddleware`` hands ``MessageMiddleware`` the calling tab's session,
# ``SessionStorage`` scopes the queue to the tab that raised it.
MESSAGE_STORAGE = 'django.contrib.messages.storage.session.SessionStorage'

