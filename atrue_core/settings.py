def _assert_production_database():
    """Fail loudly rather than serving production traffic off SQLite.

    Scenario 6 requires that no SQLite dependency remains in the production
    database configuration. Debug=False is the signal that a process is serving
    real traffic (local development runs with DEBUG=True), so a missing
    DB_PASSWORD / DB_ENGINE=sqlite here is a configuration mistake worth
    crashing on instead of quietly persisting to a local file.
    """
    if DEBUG:
        return
    default = DATABASES['default']
    if 'postgres' not in default.get('ENGINE', ''):
        raise RuntimeError(
            'DATABASES["default"] must use the PostgreSQL backend when DEBUG is '
            'False. Configure DB_NAME/DB_USER/DB_PASSWORD/DB_HOST/DB_PORT (or '
            'DATABASE_URL on Render) instead of falling back to SQLite.'
        )


_assert_production_database()



